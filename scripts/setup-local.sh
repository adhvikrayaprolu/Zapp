#!/usr/bin/env bash
# One-time local setup for the Zapp demo. Safe to re-run: existing .env files
# are never overwritten, and the demo account is reset to the same data.
#
#   ./scripts/setup-local.sh
#   ./scripts/dev.sh          # then start both servers
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
BACKEND="$ROOT/backend"
FRONTEND="$ROOT/frontend"
PYTHON="${PYTHON:-python3.13}"

say() { printf '\n\033[1;36m==> %s\033[0m\n' "$*"; }

command -v "$PYTHON" >/dev/null || { echo "Python 3.13 not found (set PYTHON=/path/to/python3.13)"; exit 1; }
command -v node >/dev/null || { echo "Node 20+ not found"; exit 1; }
NODE_MAJOR="$(node -p 'process.versions.node.split(".")[0]')"
[ "$NODE_MAJOR" -ge 20 ] || { echo "Node 20+ required (found $(node -v))"; exit 1; }

say "Backend: virtualenv + dependencies"
[ -d "$BACKEND/.venv" ] || "$PYTHON" -m venv "$BACKEND/.venv"
"$BACKEND/.venv/bin/python" -m pip install -q --upgrade pip
"$BACKEND/.venv/bin/pip" install -q -r "$BACKEND/requirements.txt"

if [ -f "$BACKEND/.env" ]; then
  say "Backend: keeping existing backend/.env"
else
  say "Backend: writing backend/.env (local-only generated keys, SQLite)"
  gen_secret() { "$BACKEND/.venv/bin/python" -c "import secrets; print(secrets.token_urlsafe(50))"; }
  gen_fernet() { "$BACKEND/.venv/bin/python" -c "from cryptography.fernet import Fernet; print(Fernet.generate_key().decode())"; }
  cat > "$BACKEND/.env" <<EOF
# Local development only. Generated by scripts/setup-local.sh; not real credentials.
SECRET_KEY=$(gen_secret)
DATABASE_URL=sqlite:///db.sqlite3
ALLOWED_HOSTS=127.0.0.1,localhost
APP_DATA_ENCRYPTION_KEY=$(gen_fernet)
PLAID_TOKEN_ENCRYPTION_KEY=$(gen_fernet)
PRIVACY_POLICY_URL=http://127.0.0.1:5173/privacy
PRIVACY_POLICY_VERSION=1.0.0
PRIVACY_POLICY_EFFECTIVE_DATE=2026-01-01

# Optional integrations — fill in only what you want to demo live:
# OPENAI_API_KEY=            # ZappBot answers (falls back to templates without it)
# PLAID_CLIENT_ID= / PLAID_SECRET= / PLAID_ENV=sandbox
# SUPABASE_URL= / SUPABASE_ANON_KEY= / SUPABASE_JWT_SECRET=   # real sign-up/login
# VALUE_SCORE_BUNDLE_PATH= / VALUE_SCORE_CHECKPOINT_DIR=       # live value-score model
EOF
fi

say "Backend: migrate + seed the demo account"
cd "$BACKEND"
.venv/bin/python manage.py migrate --noinput
.venv/bin/python manage.py seed_demo

say "Frontend: dependencies"
cd "$FRONTEND"
npm ci --no-audit --no-fund

# The frontend needs no local env file: in development it calls its own origin and
# Vite proxies /api to Django. See frontend/.env.example for optional settings.

say "Done. Start both servers with ./scripts/dev.sh, open http://127.0.0.1:5173/login and click \"Try the demo account\"."
